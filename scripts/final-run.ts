// Final run for docs/REPORT.md: runs every suite on the current checkout (meant to be a clean clone of the
// commit under test), records the counts, the commit and the environment in docs/results/final-run.json, and
// copies the generated result tables into docs/results/. Needs local PostgreSQL and the openssl command; it
// makes no network request.
//
// Run: npm run report:final-run

import { execFileSync, spawnSync } from 'node:child_process';
import * as fs from 'node:fs';
import * as os from 'node:os';
import * as path from 'node:path';
import pg from 'pg';

const SUITES = ['test', 'test:pg', 'test:tamper', 'test:local', 'test:experiments'] as const;
const COPIED = ['tamper-results.md', 'layer-ladder.md', 'pause-exposure.md'] as const;
const OUT = path.resolve('docs/results');

interface SuiteResult {
  suite: string;
  exitCode: number | null;
  tests: number;
  pass: number;
  fail: number;
  skipped: number;
}

function count(out: string, label: string): number {
  const m = new RegExp(`^ℹ ${label} (\\d+)$`, 'm').exec(out);
  return m === null ? -1 : Number(m[1]);
}

async function settings(): Promise<Record<string, string>> {
  const c = new pg.Client({
    host: process.env['PGHOST'] ?? '/var/run/postgresql',
    database: process.env['PGDATABASE'] ?? 'tear_test',
    ...(process.env['PGUSER'] !== undefined ? { user: process.env['PGUSER'] } : {}),
  });
  await c.connect();
  const out: Record<string, string> = {};
  for (const s of ['server_version', 'server_encoding', 'synchronous_commit', 'fsync', 'full_page_writes', 'wal_level']) {
    out[s] = String((await c.query<{ v: string }>(`SELECT current_setting('${s}') AS v`)).rows[0]!.v);
  }
  await c.end();
  return out;
}

async function main(): Promise<void> {
  const commit = execFileSync('git', ['rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
  const clean = execFileSync('git', ['status', '--porcelain', '--untracked-files=no'], { encoding: 'utf8' }).trim() === '';
  const suites: SuiteResult[] = [];
  for (const suite of SUITES) {
    const r = spawnSync('npm', ['run', suite], { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
    const out = `${r.stdout}\n${r.stderr}`;
    suites.push({ suite, exitCode: r.status, tests: count(out, 'tests'), pass: count(out, 'pass'), fail: count(out, 'fail'), skipped: count(out, 'skipped') });
    process.stdout.write(`${suite}: exit ${String(r.status)}, ${String(count(out, 'pass'))}/${String(count(out, 'tests'))} passed\n`);
  }
  fs.mkdirSync(OUT, { recursive: true });
  for (const f of COPIED) fs.copyFileSync(path.resolve('test-results', f), path.join(OUT, f));
  const result = {
    description: 'Final run of every suite for docs/REPORT.md; generated by scripts/final-run.ts.',
    commit,
    worktree_clean: clean,
    finished_at: new Date().toISOString(),
    suites,
    environment: {
      cpu: `${os.cpus()[0]?.model ?? 'unknown'} × ${String(os.cpus().length)}`,
      memory_gib: Math.round(os.totalmem() / 2 ** 30),
      kernel: `${os.type()} ${os.release()}`,
      node: process.version,
      openssl: execFileSync('openssl', ['version'], { encoding: 'utf8' }).trim(),
      checkpoint_fs_statfs_type: `0x${fs.statfsSync(os.tmpdir()).type.toString(16)}`,
      postgresql: await settings(),
    },
  };
  fs.writeFileSync(path.join(OUT, 'final-run.json'), `${JSON.stringify(result, null, 2)}\n`);
}

main().catch((err: unknown) => {
  process.stderr.write(`final run failed: ${err instanceof Error ? err.message : String(err)}\n`);
  process.exit(1);
});
