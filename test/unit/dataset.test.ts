import assert from 'node:assert/strict';
import * as fs from 'node:fs';
import { test } from 'node:test';
import { sha256Hex } from '../../src/crypto/digests.js';
import { DATASET_PATH, generateDataset } from '../../scripts/generate-dataset.js';

const DATASET_SHA256 = 'b82cbe3be7fac8e48f90071a0b060679a28240dafc26eb625284d07a1ac55ea1';

test('dataset: deterministic and identical to the committed file', async (t) => {
  await t.test('two runs give identical bytes', () => assert.equal(generateDataset(), generateDataset()));
  await t.test('the regenerated bytes match the committed file and its recorded SHA-256', () => {
    const generated = Buffer.from(generateDataset(), 'utf8');
    assert.equal(sha256Hex(generated), DATASET_SHA256);
    assert.ok(generated.equals(fs.readFileSync(DATASET_PATH)));
  });
});

test('dataset: format and content rules', async (t) => {
  const rows = generateDataset().trimEnd().split('\n').map((l) => JSON.parse(l) as Record<string, unknown>);
  await t.test('1000 steps of the four kinds', () => {
    assert.equal(rows.length, 1000);
    for (const r of rows) assert.ok(['tool_call', 'epistemic_pause', 'human_resolution', 'final_answer'].includes(String(r['kind'])));
  });
  await t.test('pauses are between 10 % and 20 % of the steps', () => {
    const share = rows.filter((r) => r['kind'] === 'epistemic_pause').length / rows.length;
    assert.ok(share >= 0.1 && share <= 0.2, String(share));
  });
  await t.test('the three argument size classes are present', () => {
    const sizes = rows.filter((r) => r['kind'] === 'tool_call').map((r) => Buffer.byteLength(JSON.stringify(r['args'])));
    assert.ok(sizes.some((s) => s <= 120) && sizes.some((s) => s > 1900 && s < 2200) && sizes.some((s) => s > 19000));
  });
  await t.test('no empty required strings, no U+0000, no URLs or e-mail addresses', () => {
    const text = generateDataset();
    assert.ok(!text.includes('\u0000') && !text.includes('\\u0000'));
    assert.ok(!/https?:|www\.|@/.test(text));
    for (const r of rows) {
      for (const k of ['task_id', 'tool_name', 'reason', 'reviewer_id', 'decision', 'response']) {
        if (k in r) assert.ok(typeof r[k] === 'string' && r[k] !== '', k);
      }
    }
  });
});
